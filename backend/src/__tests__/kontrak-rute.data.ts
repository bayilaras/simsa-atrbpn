// Kontrak akses setiap rute HTTP, diperiksa oleh kontrak-rute.contract.test.ts.
//
//   proyeksi       daftar, agregat, atau cetakan; saringan akses ada di query yang dipanggil `lewat`
//   checkRead      satu rekaman; data dikirim setelah gerbang baca di `lewat`
//   check          mengubah atau mengelola rekaman yang sudah ada; gerbang per rekaman di `lewat`
//   buat           membuat rekaman baru tanpa membaca rekaman lain
//   bukan-rekaman  tidak membaca atau menulis isi surat dan arsip
//
// `lewat` adalah teks persis di handler. Kontrak mencatat letak gerbang dan
// memaksa rute baru diklasifikasi; perilaku gerbangnya diuji di tes integrasi.

export const AKSES = ['proyeksi', 'checkRead', 'check', 'buat', 'bukan-rekaman'] as const;
export type Akses = (typeof AKSES)[number];

export interface EntriKontrak {
    akses: Akses;
    lewat?: string;
}

